-- Database and schemas: one schema per layer
CREATE DATABASE IF NOT EXISTS CUSTOMER360_DB;
CREATE SCHEMA IF NOT EXISTS CUSTOMER360_DB.RAW;
CREATE SCHEMA IF NOT EXISTS CUSTOMER360_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS CUSTOMER360_DB.ANALYTICS;

-- Compute: smallest size, switches itself off after 60 seconds idle
CREATE WAREHOUSE IF NOT EXISTS CUSTOMER360_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- File format for the Olist CSVs
CREATE OR REPLACE FILE FORMAT CUSTOMER360_DB.RAW.CSV_FORMAT
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL')
    EMPTY_FIELD_AS_NULL = TRUE;

-- Internal stage: a holding area where uploaded files wait to be loaded
CREATE STAGE IF NOT EXISTS CUSTOMER360_DB.RAW.OLIST_STAGE
    FILE_FORMAT = CUSTOMER360_DB.RAW.CSV_FORMAT;